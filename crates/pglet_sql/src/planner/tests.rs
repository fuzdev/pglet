/// The cast the pass writes over a subquery is written under a fold and nowhere else: a
/// subquery outside one stays bare, whatever its column is, and no reader of the pass
/// turns on its type there. Under a fold it is written over a certain subquery wherever
/// it stands — a branch, an operand of a branch, a `CASE` condition's operand — and over
/// a guessed one standing as a branch only.
#[test]
fn the_pass_casts_a_subquery_under_a_fold_and_nowhere_else() {
    fn casts(expr: &Expr, found: &mut (usize, usize)) {
        match expr {
            Expr::Cast { expr: inner, .. } if matches!(**inner, Expr::Subquery { .. }) => {
                found.0 += 1;
                return;
            }
            Expr::Subquery { .. } => found.1 += 1,
            _ => {}
        }
        expr.for_each_child(|child| casts(child, found));
    }
    let schema = scalar_subquery_schema();
    let guess = "(SELECT max(x) FROM unnest(ARRAY[1, 2.5]) q0(x))";
    for (sql, cast, bare) in [
        (
            "SELECT (SELECT 1), f + (SELECT 1), abs((SELECT 1)) FROM t".to_string(),
            0,
            3,
        ),
        ("SELECT k FROM t WHERE i = (SELECT 1)".to_string(), 0, 1),
        (
            "SELECT COALESCE((SELECT 1), 0), COALESCE(i, f + (SELECT 1)) FROM t".to_string(),
            2,
            0,
        ),
        (
            "SELECT CASE WHEN (SELECT 1) = k THEN abs(-(SELECT 2)) ELSE 0 END FROM t".to_string(),
            2,
            0,
        ),
        (
            "SELECT greatest(i, (SELECT 1) + 1), ARRAY[(SELECT 1) * 2] FROM t".to_string(),
            2,
            0,
        ),
        // a guess: cast as a branch, from the type its references resolve to, and left
        // bare as an operand
        (
            format!("SELECT COALESCE({guess}, 0), COALESCE(i, f + {guess}) FROM t"),
            1,
            1,
        ),
        // a subquery already under a cast is left as it is
        (
            "SELECT COALESCE((SELECT 1)::bigint, 0) FROM t".to_string(),
            1,
            0,
        ),
    ] {
        let plan = plan_select(&schema, &sql);
        let mut found = (0, 0);
        let mut walk = |plan: &Plan| match plan {
            Plan::Project { exprs, .. } => exprs.iter().for_each(|e| casts(e, &mut found)),
            Plan::Filter { predicate, .. } => casts(predicate, &mut found),
            _ => {}
        };
        let mut node = &plan;
        loop {
            walk(node);
            match node {
                Plan::Project { input, .. } | Plan::Filter { input, .. } => node = input,
                _ => break,
            }
        }
        assert_eq!(found, (cast, bare), "{sql}");
    }
}

/// A **branch** subquery is typed by its sub-plan's own column where that is certain,
/// before the pass's branch reader is asked: a wildcard over a function scan, which that
/// reader declines and would leave bare (`EDGES.md` row 152), is cast to its certain
/// column's type and its fold resolved. An enum's column and a `name` one are answered at
/// no position, no cast naming either type.
#[test]
fn a_branch_subquery_is_typed_by_its_sub_plans_certain_column() {
    let mut schema = scalar_subquery_schema();
    for sql in [
        "CREATE TYPE mood AS ENUM ('sad', 'ok')",
        "CREATE TABLE e (m mood)",
    ] {
        let p = plan_select(&schema, sql);
        crate::executor::execute(&p, &mut schema).unwrap();
    }
    let (y, n) = (true, false);
    for (sql, want, declared) in [
        (
            "SELECT * FROM unnest('{1.5}'::float8[])",
            y,
            TypeOid::Float8,
        ),
        (
            "SELECT (SELECT * FROM unnest('{1.5}'::float8[])) FROM t",
            y,
            TypeOid::Float8,
        ),
        (
            "SELECT (SELECT * FROM unnest('{1}'::int[])) + 1 FROM t",
            y,
            TypeOid::Int4,
        ),
        (
            "SELECT COALESCE((SELECT * FROM unnest('{1.5}'::float8[])), 2.5) FROM t",
            y,
            TypeOid::Float8,
        ),
        (
            "SELECT COALESCE((SELECT * FROM unnest('{1}'::int[])), 2.5) FROM t",
            y,
            TypeOid::Numeric,
        ),
        (
            "SELECT greatest((SELECT * FROM unnest('{1}'::int[])), 5000000000) FROM t",
            y,
            TypeOid::Int8,
        ),
        // the constructor's `unnest` column is a guess: the wildcard subquery over it is
        // left bare, and its fold deferred
        (
            "SELECT COALESCE((SELECT * FROM unnest(ARRAY[1])), 2.5) FROM t",
            n,
            TypeOid::Int4,
        ),
        ("SELECT m FROM e", y, TypeOid::Text),
        ("SELECT (SELECT m FROM e LIMIT 1) FROM t", n, TypeOid::Text),
        (
            "SELECT COALESCE((SELECT m FROM e LIMIT 1), 'ok') FROM t",
            n,
            TypeOid::Text,
        ),
        ("SELECT (SELECT current_user) FROM t", n, TypeOid::Name),
    ] {
        let columns = plan_select(&schema, sql).output_columns(&schema);
        assert_eq!(
            (columns[0].type_certain, columns[0].type_oid),
            (want, declared),
            "{sql}"
        );
    }
}

/// A nest of scalar subqueries is read in one descent of the nest at each level: the
/// entry reader asks a sub-plan's descriptor, and never the pass's branch reader, whose
/// own walk derives a nested subquery's type more than once a level. Asked for every
/// subquery, a nest of this depth does not finish planning.
#[test]
fn a_scalar_subquery_nest_is_read_in_one_descent_a_level() {
    assert_eq!(nest_certainty("SELECT {NEST} AS x"), [true]);
}

/// The same nest as a **branch** of a fold: where the nest's column is certain the pass
/// writes its cast from the sub-plan's descriptor and the branch reader is not asked at
/// all, at any level — so a fold over a nest plans in one descent a level too, where
/// asking that reader first does not finish at this depth.
#[test]
fn a_fold_over_a_certain_subquery_nest_does_not_ask_the_branch_reader() {
    for fold in [
        "SELECT COALESCE({NEST}, 2) AS x",
        "SELECT ARRAY[{NEST}, 2] AS x",
        "SELECT CASE WHEN true THEN {NEST} ELSE {NEST} END AS x",
        "SELECT greatest({NEST}, 2) AS x",
        "SELECT x FROM (SELECT nullif({NEST}, 2) AS x) q",
        "SELECT COALESCE(1 + {NEST}, 2) AS x",
    ] {
        assert_eq!(nest_certainty(fold), [true], "{fold}");
    }
    let schema = scalar_subquery_schema();
    let certain_reads = |sql: &str| {
        let sql = sql.replace("{NEST}", &subquery_nest(8, "1"));
        coercion::CERTAIN_SUBQUERY_READS.with(|reads| reads.set(0));
        assert_eq!(resolved_subquery_reads(&schema, &sql), 0, "{sql}");
        coercion::CERTAIN_SUBQUERY_READS.with(std::cell::Cell::get)
    };
    // and an `ARRAY[…]` element is read once, as a `COALESCE` branch is
    let coalesce = certain_reads("SELECT COALESCE({NEST}, 2) FROM t");
    assert_eq!(certain_reads("SELECT ARRAY[{NEST}, 2] FROM t"), coalesce);
    assert_eq!(certain_reads("SELECT greatest({NEST}, 2) FROM t"), coalesce);
    assert!(certain_reads("SELECT avg(COALESCE({NEST}, 2)) FROM t") >= coalesce);
}

/// Over a nest whose column is a **guess** — its innermost entry an enclosing query's
/// column — the pass asks its branch reader once for each branch subquery of a fold and
/// the reading that records a certainty does not ask it. That reader asks about a nested
/// subquery three times a level and derives it once (`EDGES.md` row 310), so one ask
/// over a nest of depth `d` is `d` reads, where deriving it at each ask was
/// `(3^d - 1) / 2`.
#[test]
fn a_fold_over_a_guessed_subquery_nest_asks_the_branch_reader_once_a_branch() {
    const DEPTH: u32 = 6;
    let one_ask = DEPTH as usize;
    let schema = scalar_subquery_schema();
    let nest = subquery_nest(DEPTH as usize, "t.i");
    for (sql, asks) in [
        ("SELECT {NEST} FROM t", 0),
        ("SELECT 1 + {NEST} FROM t", 0),
        ("SELECT COALESCE({NEST}, 2) FROM t", 1),
        ("SELECT COALESCE(1 + {NEST}, 2) FROM t", 0),
        ("SELECT ARRAY[{NEST}, 2] FROM t", 1),
        ("SELECT greatest({NEST}, 2) FROM t", 1),
        ("SELECT nullif({NEST}, 2) FROM t", 1),
        (
            "SELECT CASE WHEN true THEN {NEST} ELSE {NEST} END FROM t",
            2,
        ),
        ("SELECT avg(COALESCE({NEST}, 2)) FROM t", 1),
        (
            "SELECT x FROM (SELECT COALESCE({NEST}, 2) AS x FROM t) q",
            1,
        ),
    ] {
        let sql = sql.replace("{NEST}", &nest);
        assert_eq!(
            resolved_subquery_reads(&schema, &sql),
            asks * one_ask,
            "{sql}"
        );
    }
}

/// A fold over a nest whose innermost entry names an **enclosing** enum column is a
/// branch no cast can carry, so the pass leaves it bare and the unification gate asks the
/// branch reader about it again — and each ask is one descent of the nest, so a nest of
/// this depth plans, where deriving a nested subquery at every ask does not finish.
#[test]
fn a_fold_over_an_enclosing_enum_nest_plans_in_one_descent_a_level() {
    let (done, planned) = std::sync::mpsc::channel();
    std::thread::Builder::new()
        .stack_size(64 * 1024 * 1024)
        .spawn(move || {
            let mut schema = Schema::new();
            for sql in [
                "CREATE TYPE mood AS ENUM ('sad', 'ok', 'happy')",
                "CREATE TABLE te (m mood, k INT)",
                "CREATE TABLE tt (m TEXT)",
            ] {
                let p = plan_select(&schema, sql);
                crate::executor::execute(&p, &mut schema).unwrap();
            }
            let nest = format!(
                "{}(SELECT o.m FROM tt){}",
                "(SELECT ".repeat(39),
                " FROM tt)".repeat(39)
            );
            let planned = |literal: &str| {
                parse(
                    &format!("SELECT COALESCE({nest}, {literal}) FROM te o"),
                    &schema,
                )
                .map(|_| ())
                .map_err(|e| e.sqlstate().to_owned())
            };
            let _ = done.send([planned("'happy'"), planned("'zzz'")]);
        })
        .unwrap();
    let answers = planned
        .recv_timeout(std::time::Duration::from_secs(60))
        .expect("a fold over an enclosing enum nest plans in time");
    // and the enum is what the literal is read as: `zzz` is no label
    assert_eq!(answers, [Ok(()), Err("22P02".to_owned())]);
}

/// `depth` scalar subqueries, each selecting the next, the innermost selecting `core`.
fn subquery_nest(depth: usize, core: &str) -> String {
    format!("{}{core}{}", "(SELECT ".repeat(depth), ")".repeat(depth))
}

/// How many times planning `sql` asks the pass's branch reader for a subquery's type.
fn resolved_subquery_reads(schema: &Schema, sql: &str) -> usize {
    coercion::RESOLVED_SUBQUERY_READS.with(|reads| reads.set(0));
    let _ = parse(sql, schema);
    coercion::RESOLVED_SUBQUERY_READS.with(std::cell::Cell::get)
}

/// The certainty of each column of `sql` with `{NEST}` a nest of scalar subqueries too
/// deep to plan unless each level reads it in one descent — planned on its own thread,
/// which a reading that does not finish leaves behind.
fn nest_certainty(sql: &str) -> Vec<bool> {
    let sql = sql.replace("{NEST}", &subquery_nest(40, "1"));
    let (done, planned) = std::sync::mpsc::channel();
    std::thread::Builder::new()
        .stack_size(64 * 1024 * 1024)
        .spawn(move || {
            let schema = Schema::new();
            let _ = done.send(certain_flags(&schema, &sql));
        })
        .unwrap();
    planned
        .recv_timeout(std::time::Duration::from_secs(60))
        .expect("a nest of scalar subqueries plans in time")
}

/// An aggregate's verdict is read off its argument as written wherever the pass writes
/// its own branch casts — a `HAVING` and a sort key as well as the select list: over a
/// subquery branch whose sub-plan is a guess the argument is not a certain integer,
/// though the cast the pass then writes over that branch names one.
#[test]
fn an_aggregates_verdict_does_not_read_the_pass_own_branch_cast() {
    fn verdicts(expr: &Expr, found: &mut Vec<ArgCertainty>) {
        if let Expr::Aggregate { certainty, .. } = expr {
            found.push(*certainty);
        }
        expr.for_each_child(|child| verdicts(child, found));
    }
    // a sort key holding an aggregate is appended to the grouping node's entries
    fn having_verdicts(plan: &Plan, found: &mut Vec<ArgCertainty>) {
        match plan {
            Plan::Aggregate {
                having,
                exprs,
                input,
                ..
            } => {
                for expr in having.iter().chain(exprs) {
                    verdicts(expr, found);
                }
                having_verdicts(input, found);
            }
            Plan::Sort { input, .. }
            | Plan::Project { input, .. }
            | Plan::JunkFilter { input, .. }
            | Plan::Limit { input, .. } => having_verdicts(input, found),
            _ => {}
        }
    }
    let schema = scalar_subquery_schema();
    let guess = "(SELECT max(x) FROM unnest(ARRAY[1, 2.5]) q0(x))";
    for (clause, want) in [
        (
            format!("HAVING avg(COALESCE({guess}, i)) > 0"),
            ArgCertainty::NotCertainInteger,
        ),
        (
            "HAVING avg(COALESCE((SELECT 1), i)) > 0".to_string(),
            ArgCertainty::CertainInteger(TypeOid::Int4),
        ),
        (
            format!("ORDER BY sum(COALESCE({guess}, b))"),
            ArgCertainty::NotCertainInteger,
        ),
        (
            "ORDER BY sum(COALESCE((SELECT 5000000000), b))".to_string(),
            ArgCertainty::CertainInteger(TypeOid::Int8),
        ),
    ] {
        let sql = format!("SELECT k FROM t GROUP BY k {clause}");
        let mut found = Vec::new();
        having_verdicts(&plan_select(&schema, &sql), &mut found);
        assert!(found.contains(&want), "{sql}: {found:?}");
        assert!(
            !found.contains(&ArgCertainty::Undecided),
            "{sql}: {found:?}"
        );
    }
}
