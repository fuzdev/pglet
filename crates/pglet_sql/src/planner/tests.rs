/// The scan node under a top-level `Project` (no `Sort` is expected on the
/// elision path, so — unlike `from_source` — this panics if a `Sort` survives).
fn project_input(plan: Plan) -> Plan {
    let Plan::Project { input, .. } = plan else {
        panic!("expected a Project over the scan, got {plan:?}");
    };
    *input
}

