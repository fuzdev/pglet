#[test]
fn identity_always_column_is_serial_not_null() {
    use crate::catalog::IdentityGeneration;
    let schema = Schema::new();
    let plan = plan_select(
        &schema,
        "CREATE TABLE t (id int GENERATED ALWAYS AS IDENTITY, name text)",
    );
    let Plan::CreateTable { columns, .. } = plan else {
        panic!("expected CreateTable plan");
    };
    // An identity column is a SERIAL (implicit sequence, implicitly NOT NULL) plus
    // the ALWAYS flag; no `START WITH` seeds the default (1).
    assert_eq!(columns[0].identity, Some(IdentityGeneration::Always));
    assert!(!columns[0].nullable);
    assert_eq!(columns[0].identity_start, None);
    // The parse side says *implicit sequence* and leaves `default` empty: the name is
    // the engine's, minted at execute time against the live relation namespace so it
    // can be disambiguated. A `String` decided here could not be.
    assert!(columns[0].implicit_sequence);
    assert!(columns[0].default.is_none());
}

