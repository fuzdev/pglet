/// A projected expression resolves its columns against the plan node's **input
/// relations**, not the catalog — so a FROM-clause alias, a derived table, a CTE
/// reference and a join all type their operands.
///
/// The hermetic twin of `tests/fixtures/select/alias_*_declared_types.sql`. Resolving
/// through the catalog by name typed nothing behind an alias (`schema.get_table("m")`
/// is `None`), and the arithmetic node then answered from whatever it had: `text` when
/// neither operand resolved, the *other* operand's type when one did. Both are wrong
/// **types over correct bytes**, which is a binary client's decode failure.
#[test]
fn a_projected_expression_types_against_the_input_relations() {
    let schema = schema_with_mixed_widths();
    for (sql, want) in [
        // Unaliased — the polarity pin: already correct, must stay correct.
        ("SELECT s + i FROM mw", TypeOid::Int4),
        ("SELECT s + b FROM mw", TypeOid::Int8),
        // Base scan behind an alias, qualified and unqualified alike.
        ("SELECT m.s + m.i FROM mw m", TypeOid::Int4),
        ("SELECT s + b FROM mw m", TypeOid::Int8),
        // The other-operand fallback: `0` is int4, the column int8.
        ("SELECT m.b + 0 FROM mw m", TypeOid::Int8),
        // A derived table and a CTE reference name relations the catalog cannot have.
        (
            "SELECT x.a + x.d FROM (SELECT s AS a, b AS d FROM mw) x",
            TypeOid::Int8,
        ),
        (
            "WITH c AS (SELECT s AS a, b AS d FROM mw) SELECT c.a + c.d FROM c",
            TypeOid::Int8,
        ),
        // A join has no single table to fall back to at all.
        (
            "SELECT m.s + n.b FROM mw m JOIN mw n ON true",
            TypeOid::Int8,
        ),
    ] {
        assert_eq!(declared_type(&schema, sql), want, "declared type for {sql}");
    }
}

/// The `Aggregate` and `Window` nodes build their output descriptors on their own
