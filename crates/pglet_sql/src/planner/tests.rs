/// An index over an enum column is ordered by the **label bytes** — the B-tree key
/// encoder has no enum arm — while every comparison beside it orders by member
/// position, so serving any read from it is a different answer, not a faster one.
///
/// A differential fixture sees the *answers* and so cannot see which plan produced
/// them: after this decline both plans answer correctly, and `enum/*_indexed_*.sql`
/// would stay green if the decline were replaced by an accidentally-correct index.
/// This asserts the plan.
///
/// Vacuous in the stripped build, which declines every index — which is what the `text`
/// control below (acceleration-only) is for.
#[test]
fn enum_indexed_col_is_declined() {
    let schema = schema_with_enum_and_text_indexes();
    // The ordered scan (`Sort` elision) — the route with the NOT-NULL gate.
    for sql in [
        "SELECT * FROM e ORDER BY m",
        "SELECT * FROM e ORDER BY m DESC",
    ] {
        assert_sort_kept(&plan_select(&schema, sql), sql);
    }
    // ...and the equality/range probes, which fire with no NOT-NULL gate at all.
    for sql in [
        "SELECT * FROM e WHERE m = 'ok'",
        "SELECT * FROM e WHERE m > 'sad'",
        "SELECT * FROM e WHERE m BETWEEN 'ok' AND 'happy'",
    ] {
        match project_input(plan_select(&schema, sql)) {
            Plan::Filter { input, .. } => assert!(
                matches!(*input, Plan::Scan { .. }),
                "an enum key column must not be probed: `{sql}`"
            ),
            other => panic!("expected Filter(Scan) for `{sql}`, got {other:?}"),
        }
    }
}

