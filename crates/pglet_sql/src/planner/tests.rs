#[test]
fn test_plan_begin_transaction_modes() {
    use crate::executor::IsolationLevel;
    let schema = Schema::new();
    // `gram.y`'s `transaction_mode_list`: any order, any combination, comma
    // optional. Every one of these is accepted on 18.6, measured.
    for sql in [
        "BEGIN ISOLATION LEVEL SERIALIZABLE",
        "BEGIN ISOLATION LEVEL REPEATABLE READ",
        "BEGIN ISOLATION LEVEL READ COMMITTED",
        "BEGIN ISOLATION LEVEL READ UNCOMMITTED",
        "BEGIN TRANSACTION ISOLATION LEVEL SERIALIZABLE READ WRITE",
        "BEGIN WORK ISOLATION LEVEL SERIALIZABLE, READ WRITE, NOT DEFERRABLE",
        "BEGIN DEFERRABLE",
        "BEGIN NOT DEFERRABLE",
        "BEGIN READ WRITE",
        "begin read write, isolation level serializable",
        "START TRANSACTION ISOLATION LEVEL SERIALIZABLE, READ WRITE",
        "START TRANSACTION DEFERRABLE ISOLATION LEVEL REPEATABLE READ",
    ] {
        assert!(
            matches!(plan_select(&schema, sql), Plan::BeginTransaction { .. }),
            "{sql}"
        );
    }
    // The level rides the plan to the host, the last one written winning — 18.6 applies
    // the list in order.
    for (sql, want) in [
        ("BEGIN", None),
        ("BEGIN READ WRITE", None),
        (
            "BEGIN ISOLATION LEVEL REPEATABLE READ",
            Some(IsolationLevel::RepeatableRead),
        ),
        (
            "START TRANSACTION DEFERRABLE ISOLATION LEVEL SERIALIZABLE",
            Some(IsolationLevel::Serializable),
        ),
        (
            "BEGIN ISOLATION LEVEL SERIALIZABLE, ISOLATION LEVEL READ UNCOMMITTED",
            Some(IsolationLevel::ReadUncommitted),
        ),
    ] {
        let Plan::BeginTransaction { isolation } = plan_select(&schema, sql) else {
            panic!("{sql}");
        };
        assert_eq!(isolation, want, "{sql}");
    }
}

#[test]
fn test_plan_begin_read_only_is_refused_loud() {
    // The one mode that is *not* accepted-and-inert. pglet has no read-only block,
    // so accepting the request and then executing the write it forbids answers
    // success where 18.6 answers `25006` — a silent over-acceptance. Refusing is
    // what cannot write. (18.6 accepts all four spellings, so no differential
    // fixture can pin the code; this is where it lives.)
    let schema = Schema::new();
    for sql in [
        "BEGIN READ ONLY",
        "BEGIN TRANSACTION READ ONLY",
        "START TRANSACTION READ ONLY",
        "START TRANSACTION ISOLATION LEVEL SERIALIZABLE, READ ONLY, DEFERRABLE",
    ] {
        let err = crate::parser::parse_single(sql, &schema).expect_err(sql);
        assert_eq!(err.sqlstate(), "0A000", "{sql}");
        assert_eq!(
            err.to_string(),
            "not implemented: READ ONLY transactions are not supported",
            "{sql}"
        );
    }
}

