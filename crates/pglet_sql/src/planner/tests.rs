#[test]
fn on_conflict_do_update_always_identity_fails_loud() {
    use crate::catalog::{Column, IdentityGeneration, Table};
    use crate::types::TypeOid;
    let mut schema = Schema::new();
    let col = |name: &str, type_oid, position, identity| Column {
        name: name.to_string(),
        type_oid,
        nullable: false,
        position,
        default: None,
        enum_type: None,
        numeric_typmod: None,
        varchar_length: None,
        temporal_precision: None,
        identity,
    };
    schema.create_table(Table {
        name: "t".to_string(),
        schema: "public".to_string(),
        columns: vec![
            col("id", TypeOid::Int4, 1, Some(IdentityGeneration::Always)),
            col("name", TypeOid::Text, 2, None),
        ],
        oid: 1,
        checks: vec![],
        foreign_keys: vec![],
    });
    // The DO UPDATE assignment path (which never routes through `lower_update`) must
    // still reject setting a GENERATED ALWAYS column to a non-DEFAULT value (428C9).
    let err = parse(
        "INSERT INTO t (name) VALUES ('b') ON CONFLICT (id) DO UPDATE SET id = 99",
        &schema,
    )
    .unwrap_err();
    assert_eq!(err.sqlstate(), "428C9");

    // `SET id = DEFAULT` on the same column is allowed (parses cleanly).
    assert!(
        parse(
            "INSERT INTO t (name) VALUES ('b') ON CONFLICT (id) DO UPDATE SET id = DEFAULT",
            &schema,
        )
        .is_ok()
    );
}

