/// A junk column is added only when a key needs one — the plan-shape half of the
/// rule, which no differential fixture can see.
///
/// Every fixture in the family compares *rows*, and a `JunkFilter` that trimmed
/// nothing would leave every row identical: the guard against wrapping every
/// aggregated query in a redundant node has to be a plan-shape assertion.
#[test]
fn an_order_by_the_aggregate_output_answers_adds_no_junk_column() {
    let schema = schema_with_group_table();
    for sql in [
        "SELECT k, count(*) FROM gj GROUP BY k ORDER BY k",
        "SELECT k, count(*) AS c FROM gj GROUP BY k ORDER BY c DESC",
        "SELECT k, count(*) FROM gj GROUP BY k ORDER BY count(*)",
        "SELECT k, count(*) FROM gj GROUP BY k ORDER BY 2",
        "SELECT k, count(*) FROM gj GROUP BY k",
    ] {
        let p = plan_select(&schema, sql);
        assert!(
            !matches!(p, Plan::JunkFilter { .. }),
            "no junk column is owed by `{sql}`, got {p:?}"
        );
    }
}

/// The junk trim sits **above** the Sort that reads the junk column and **below** the
/// Limit, and it trims back to the select list's own width.
///
/// Both halves are invisible to the corpus: trimming under the Sort loses the key
/// (which a fixture would catch as a wrong order, but only for the keys it happens to
/// use), and the Limit reads no column at all, so its position relative to the trim
/// never changes a row.
#[test]
fn a_junk_key_trims_above_the_sort_and_below_the_limit() {
    let schema = schema_with_group_table();
    let p = plan_select(
        &schema,
        "SELECT count(*) FROM gj GROUP BY k ORDER BY min(v), k LIMIT 2",
    );
    let Plan::Limit { input, .. } = p else {
        panic!("expected the Limit on top, got {p:?}");
    };
    let Plan::JunkFilter { input, keep } = *input else {
        panic!("expected a JunkFilter under the Limit, got {input:?}");
    };
    assert_eq!(keep, 1, "the select list is one column wide");
    let Plan::Sort {
        input, order_by, ..
    } = *input
    else {
        panic!("expected the Sort under the JunkFilter, got {input:?}");
    };
    assert_eq!(order_by.len(), 2);
    let Plan::Aggregate { exprs, .. } = *input else {
        panic!("expected the Aggregate under the Sort, got {input:?}");
    };
    assert_eq!(
        exprs.len(),
        3,
        "one select-list expression plus two junk columns"
    );
    // The two junk columns carry distinct names, which is what the Sort's by-name read
    // of them rests on — and the Sort reads *those* names, so a minter that renamed one
    // without telling the key would leave the key resolving off something else.
    let names: Vec<String> = exprs.iter().map(Expr::output_name).collect();
    assert_eq!(
        &names[1..],
        ["pglet_junk_0", "pglet_junk_1"],
        "the two junk columns take the minted names in order: {names:?}"
    );
    let key_names: Vec<String> = order_by.iter().map(|k| k.expr.output_name()).collect();
    assert_eq!(
        key_names,
        names[1..],
        "both keys read their own junk column"
    );
}

#[test]
fn default_values_lowers_to_its_values_twin_plan() {
    use crate::catalog::{Column, Table};
    // `INSERT … DEFAULT VALUES` is `parser::dml`'s one empty `VALUES` tuple, widened to
    // table width by `lower_insert_rows`. The claim that follows from that — that the
    // clauses hanging off the row source (`RETURNING`, `ON CONFLICT`, and the
    // correlated re-walk `walk_level`'s `Plan::Insert` arm drives) need no new arm — is
    // a claim about the **plan**, and the differential corpus compares answers. So the
    // structural half is asserted here: the row-less spelling and its all-`DEFAULT`
    // twin lower to equal `Plan`s, clause for clause. A lowering that produced any
    // other shape could still answer identically on today's fixtures and diverge on the
    // first clause reader that matches on it.
    let mut schema = Schema::new();
    let col = |name: &str, type_oid, position| Column {
        name: name.to_string(),
        type_oid,
        nullable: true,
        position,
        default: None,
        enum_type: None,
        numeric_typmod: None,
        varchar_length: None,
        temporal_precision: None,
        identity: None,
    };
    schema.create_table(Table {
        name: "dvt".to_string(),
        schema: "public".to_string(),
        columns: vec![
            col("id", TypeOid::Int4, 1),
            col("v", TypeOid::Text, 2),
            col("n", TypeOid::Int4, 3),
        ],
        oid: 1,
        checks: vec![],
        foreign_keys: vec![],
    });
    let twins = [
        (
            "INSERT INTO dvt DEFAULT VALUES",
            "INSERT INTO dvt VALUES (DEFAULT, DEFAULT, DEFAULT)",
        ),
        (
            "INSERT INTO dvt DEFAULT VALUES RETURNING *",
            "INSERT INTO dvt VALUES (DEFAULT, DEFAULT, DEFAULT) RETURNING *",
        ),
        (
            "INSERT INTO dvt DEFAULT VALUES ON CONFLICT (id) DO UPDATE SET v = 'u' RETURNING id, v",
            "INSERT INTO dvt VALUES (DEFAULT, DEFAULT, DEFAULT) \
             ON CONFLICT (id) DO UPDATE SET v = 'u' RETURNING id, v",
        ),
    ];
    for (row_less, spelled_out) in twins {
        assert_eq!(
            parse(row_less, &schema).unwrap(),
            parse(spelled_out, &schema).unwrap(),
            "{row_less} should lower to the plan of {spelled_out}",
        );
    }
    // The omitted-cell path is the same widening, so a *short* tuple is the twin too —
    // which is what identifies the widening as the mechanism rather than a row-less
    // special case somewhere downstream.
    assert_eq!(
        parse("INSERT INTO dvt DEFAULT VALUES", &schema).unwrap(),
        parse("INSERT INTO dvt (id) VALUES (DEFAULT)", &schema).unwrap(),
    );
}

/// A plan describes a column certain ([`ColumnDesc::type_certain`]) exactly where the
/// coercion pass read the expression defining it, as written, at the type the plan
/// declares for it — which is what a query reading the plan as a relation takes the
/// column's certainty from. Both polarities per shape: a base column and the entries
/// the pass types — a `date - date` and a fold over an operand subquery whose column is
/// certain among them — beside a fold it leaves at a guess, a scalar subquery over an
/// enclosing query's columns, an untyped literal and a window function; a `VALUES` column every cell of
/// which it typed beside one holding a guessed cell; a set operation certain on both
/// sides, an untyped `NULL` side taking the other's type, beside one with a guessed
/// side; a cast array's `unnest` beside an `ARRAY[…]` constructor's; a `USING` merge of
/// same-typed columns beside one of an `integer` and a `bigint`; a recursive query whose
/// two terms are certain beside one whose recursive term is an untyped `NULL`. And the
/// record stays with its target list through the plan layouts a sort gives a level. A
/// scalar subquery's own polarities are
/// [`a_scalar_subquery_is_certain_where_its_sub_plans_column_is`]'s.
#[test]
fn a_plans_columns_are_certain_where_the_pass_typed_their_definition() {
    let mut schema = Schema::new();
    for sql in [
        "CREATE TABLE t (k INT NOT NULL, i INT, b BIGINT, f FLOAT8, d DATE)",
        "CREATE INDEX t_k ON t (k)",
        "CREATE TABLE u8 (k BIGINT)",
    ] {
        let p = plan_select(&schema, sql);
        crate::executor::execute(&p, &mut schema).unwrap();
    }
    let (y, n) = (true, false);
    for (sql, want) in [
        (
            "SELECT i, i + 0, i AS z, COALESCE(i, f + (SELECT 1)), d - d, (SELECT d - d), 'a', NULL, \
             1 FROM t",
            vec![y, y, y, y, y, n, n, n, y],
        ),
        (
            "SELECT COALESCE(i, f + (SELECT * FROM unnest(ARRAY[1]))) FROM t",
            vec![n],
        ),
        // a `date` less a `date` alone: no other operator over two dates is typed
        (
            "SELECT d - d, d + d, d * d, d - 1, d - k FROM t",
            vec![y, n, n, n, n],
        ),
        ("SELECT * FROM t", vec![y, y, y, y, y]),
        (
            "SELECT * FROM t GROUP BY k, i, b, f, d",
            vec![y, y, y, y, y],
        ),
        // the record follows its target list through each layout a sort gives the level:
        // above the projection, below it, pushed into an index scan over the `NOT NULL`
        // `k` (the accelerated build's), and beside the junk columns a grouped, windowed
        // or `DISTINCT ON` level appends for its keys
        ("SELECT i + 0 AS x FROM t ORDER BY x", vec![y]),
        ("SELECT i + 0 AS x FROM t ORDER BY b, i", vec![y]),
        ("SELECT i + 0 AS x FROM t ORDER BY k", vec![y]),
        (
            "SELECT max(b) AS x FROM t GROUP BY k ORDER BY min(i)",
            vec![y],
        ),
        (
            "SELECT i + 0 AS x, row_number() OVER () FROM t ORDER BY k",
            vec![y, n],
        ),
        (
            "SELECT DISTINCT ON (k) i + 0 AS x FROM t ORDER BY k, b",
            vec![y],
        ),
        (
            "SELECT max(b), count(*), sum(i), avg(i), max(d - d), k FROM t GROUP BY k",
            vec![y, y, y, y, y, y],
        ),
        ("SELECT row_number() OVER (), i + 0 FROM t", vec![n, y]),
        (
            "SELECT x, y FROM (VALUES (1, COALESCE(1, 2.5 + (SELECT * FROM unnest(ARRAY[1])))), \
             (5000000000, 2)) v(x, y)",
            vec![y, n],
        ),
        ("SELECT x FROM (VALUES (1), ('2'), (NULL)) v(x)", vec![y]),
        ("SELECT i FROM t UNION ALL SELECT b FROM t", vec![y]),
        ("SELECT i FROM t UNION ALL SELECT NULL", vec![y]),
        (
            "SELECT i FROM t UNION ALL \
             SELECT COALESCE(i, f + (SELECT * FROM unnest(ARRAY[1]))) FROM t",
            vec![n],
        ),
        (
            "SELECT COALESCE(i, f + (SELECT * FROM unnest(ARRAY[1]))) FROM t UNION ALL \
             SELECT i FROM t",
            vec![n],
        ),
        ("SELECT x FROM unnest('{1}'::int[]) q(x)", vec![y]),
        ("SELECT x FROM unnest(ARRAY[1]) q(x)", vec![n]),
        ("SELECT k FROM t a JOIN t b USING (k)", vec![y]),
        ("SELECT k FROM t JOIN u8 USING (k)", vec![n]),
        (
            "WITH RECURSIVE r(x) AS (SELECT 1 UNION ALL SELECT x + 1 FROM r WHERE x < 3) \
             SELECT x FROM r",
            vec![y],
        ),
        (
            "WITH RECURSIVE r(x) AS (SELECT 1 UNION ALL SELECT NULL FROM r WHERE x < 3) \
             SELECT x FROM r",
            vec![n],
        ),
        (
            "SELECT x FROM (SELECT i + 0 AS x FROM t) q ORDER BY x LIMIT 1",
            vec![y],
        ),
        (
            "SELECT x FROM (SELECT COALESCE(i, f + (SELECT * FROM unnest(ARRAY[1]))) AS x FROM t) q",
            vec![n],
        ),
    ] {
        let certain: Vec<bool> = plan_select(&schema, sql)
            .output_columns(&schema)
            .iter()
            .map(|c| c.type_certain)
            .collect();
        assert_eq!(certain, want, "{sql}");
    }
}

/// The record a plan carries is the **type** each entry was read at, and a column is
/// certain only where that is the type declared for it: an entry recorded at another
/// type — a reader and a walker that part — is not certain, and neither is one past the
/// record's end, as a junk column appended after the pass is.
#[test]
fn a_recorded_type_makes_a_column_certain_only_at_the_type_declared() {
    let schema = Schema::new();
    let describe = |certain: Vec<Option<TypeOid>>| -> Vec<bool> {
        Plan::Values {
            rows: vec![vec![
                Expr::Literal(Literal::Int(1)),
                Expr::Literal(Literal::Int(2)),
            ]],
            certain: CertainTypes::new(certain),
            enclosing: EnclosingColumns::default(),
        }
        .output_columns(&schema)
        .iter()
        .map(|c| c.type_certain)
        .collect()
    };
    assert_eq!(
        describe(vec![Some(TypeOid::Int4), Some(TypeOid::Int4)]),
        [true, true]
    );
    assert_eq!(describe(vec![Some(TypeOid::Int8), None]), [false, false]);
    assert_eq!(describe(vec![Some(TypeOid::Int4)]), [true, false]);
    assert_eq!(describe(Vec::new()), [false, false]);
}

/// The schema [`a_scalar_subquery_is_certain_where_its_sub_plans_column_is`] and its
/// neighbours plan over.
fn scalar_subquery_schema() -> Schema {
    let mut schema = Schema::new();
    for sql in [
        "CREATE TABLE t (k INT NOT NULL, i INT, b BIGINT, f FLOAT8, d DATE, n NUMERIC)",
        "CREATE TABLE u (k INT, i INT)",
        "CREATE TABLE u8 (k BIGINT)",
    ] {
        let p = plan_select(&schema, sql);
        crate::executor::execute(&p, &mut schema).unwrap();
    }
    schema
}

/// The `type_certain` flag of each output column of `sql`.
fn certain_flags(schema: &Schema, sql: &str) -> Vec<bool> {
    plan_select(schema, sql)
        .output_columns(schema)
        .iter()
        .map(|c| c.type_certain)
        .collect()
}

/// A scalar subquery is certain exactly where its sub-plan's single output column is —
/// by that sub-plan's own record, never by this level's reading of it — in each position
/// one can define a column from: the entry itself, an operand of arithmetic or of a
/// function, and a branch of a `COALESCE`, a `CASE`, a variadic or an `ARRAY[…]`.
///
/// The uncertain sub-plans are the ones whose column is a guess: a fold the pass left
/// at the written reach, an `ARRAY[…]` constructor's `unnest`, a `USING` merge of an
/// `integer` and a `bigint`, a correlated aggregate, an enclosing query's column and a
/// window function. Every one of them has a type its column references resolve to,
/// which is what the pass's branch cast is written from — so a fold over one is the
/// shape that told a record read off that cast from one read off the sub-plan.
#[test]
fn a_scalar_subquery_is_certain_where_its_sub_plans_column_is() {
    let schema = scalar_subquery_schema();
    let wrappers = [
        "{S}",
        "{S} + 1",
        "-{S}",
        "abs({S})",
        "COALESCE({S}, 0)",
        "COALESCE(NULL, {S})",
        "CASE WHEN k > 0 THEN {S} ELSE 0 END",
        "greatest({S}, 0)",
        "nullif({S}, 99)",
        "COALESCE({S}, 0) + 1",
    ];
    let certain = [
        "(SELECT 1)",
        "(SELECT max(i) FROM u)",
        "(SELECT u.i FROM u WHERE u.k = t.k)",
        "(SELECT i + 0 FROM u LIMIT 1)",
        "(SELECT x FROM (VALUES (1), (4)) v(x) LIMIT 1)",
        "(SELECT i FROM u UNION ALL SELECT 2 LIMIT 1)",
        "(SELECT avg(x) FROM (VALUES (1), (4)) v(x))",
        "(SELECT (SELECT max(i) FROM u))",
        "(SELECT COALESCE(i, f + (d - d)) FROM t t2 LIMIT 1)",
        "(SELECT COALESCE(i, f + (SELECT 1)) FROM t t2 LIMIT 1)",
        "(SELECT d - d FROM t t2 LIMIT 1)",
        "(SELECT * FROM unnest('{1}'::int[]))",
    ];
    let guessed = [
        "(SELECT COALESCE(i, f + (SELECT * FROM unnest(ARRAY[1]))) FROM t t2 LIMIT 1)",
        "(SELECT * FROM unnest(ARRAY[1.5::numeric]))",
        "(SELECT max(x) FROM unnest(ARRAY[1, 2.5]) q0(x))",
        "(SELECT max(k) FROM u FULL JOIN u8 USING (k))",
        "(SELECT avg(t.i + u.i) FROM u)",
        "(SELECT t.i)",
        "(SELECT row_number() OVER () FROM u LIMIT 1)",
        "(SELECT (SELECT t.i))",
    ];
    for (subqueries, want) in [(&certain[..], true), (&guessed[..], false)] {
        for subquery in subqueries {
            for wrapper in wrappers {
                let sql = format!("SELECT {} FROM t", wrapper.replace("{S}", subquery));
                assert_eq!(certain_flags(&schema, &sql), [want], "{sql}");
            }
            let array = format!("SELECT ARRAY[{subquery}, 0] FROM t");
            assert_eq!(certain_flags(&schema, &array), [want], "{array}");
            // a `VALUES` cell has no enclosing row to name
            if !subquery.contains("t.") {
                let cell = format!("SELECT x FROM (VALUES ({subquery}), (4)) v(x)");
                assert_eq!(certain_flags(&schema, &cell), [want], "{cell}");
            }
        }
    }
    // a cast written over a guessed subquery is a cast: certain at its target
    for subquery in guessed {
        let sql = format!("SELECT {subquery}::int FROM t");
        assert_eq!(certain_flags(&schema, &sql), [true], "{sql}");
    }
}

/// A subquery standing as an **operand** under a branch of a fold is typed where its
/// sub-plan's column is certain, as it is outside one: the pass writes its cast over
/// every such subquery under a fold, so the fold the entry reader types is one the pass's
/// own reader — which holds no catalog — types too. An operand whose column is a guess
/// is typed by neither, and its fold is left at the written reach.
#[test]
fn a_subquery_operand_under_a_fold_is_typed_where_its_column_is_certain() {
    let schema = scalar_subquery_schema();
    let (y, n) = (true, false);
    let guess = "(SELECT * FROM unnest(ARRAY[1]))";
    for (operand, want) in [("(SELECT 1)", y), (guess, n)] {
        let sql = format!(
            "SELECT f + {operand}, {operand} * i, abs({operand}), COALESCE(i, f + {operand}), \
             COALESCE({operand} + 1, 7), CASE WHEN k > 0 THEN -{operand} ELSE 0 END, \
             greatest(abs({operand}), 0), ARRAY[{operand} + 1, 7], nullif({operand} * 2, 0), \
             COALESCE(i, COALESCE({operand} + 1, 7)), avg(COALESCE(i, {operand} + 1)) FROM t \
             GROUP BY k, i, f"
        );
        assert_eq!(certain_flags(&schema, &sql), vec![want; 11], "{sql}");
    }
    // a branch subquery of a fold nested under another fold is a branch, and a fold over
    // a branch subquery an operand like any other
    assert_eq!(
        certain_flags(
            &schema,
            "SELECT COALESCE(COALESCE((SELECT 1), 2), 2.5), COALESCE(i, COALESCE((SELECT 1), 7)), \
             COALESCE((SELECT 1), 0) + f FROM t"
        ),
        [y, y, y]
    );
}

/// A `$N` no cast types is of unknown type, as an untyped `NULL` is: as a **branch** of a
/// fold it is read at the other branches' target and the pass casts it there, so the fold
/// is typed where the rest of it is — the column it defines certain, an `avg` over it
/// exact.
///
/// An unknown **operand** of arithmetic is not read at its sibling's type. No cast is
/// written over an operand, so the operator's value is what the bound value makes it —
/// a `numeric` times a bound `double precision` is a `double precision` — and a branch
/// called `numeric` there would be left uncast under that declaration. The operator is
/// untyped, the column it defines not certain, and an `avg` over it not exact.
#[test]
fn an_unknown_branch_takes_its_folds_target_and_an_unknown_operand_no_type() {
    fn verdicts(expr: &Expr, found: &mut Vec<ArgCertainty>) {
        if let Expr::Aggregate { certainty, .. } = expr {
            found.push(*certainty);
        }
        expr.for_each_child(|child| verdicts(child, found));
    }
    let schema = scalar_subquery_schema();
    for unknown in ["$1", "NULL"] {
        let sql = format!(
            "SELECT COALESCE({unknown}, f + 0), COALESCE(i + 0, {unknown}), \
             CASE WHEN k > 0 THEN {unknown} ELSE b * 1 END, greatest(i + 0, {unknown}), \
             ARRAY[{unknown}, f + 0], COALESCE(abs(COALESCE({unknown}, i + 0)), f + 0) FROM t"
        );
        let columns = plan_select(&schema, &sql).output_columns(&schema);
        let types: Vec<TypeOid> = columns.iter().map(|c| c.type_oid).collect();
        assert_eq!(
            types,
            [
                TypeOid::Float8,
                TypeOid::Int4,
                TypeOid::Int8,
                TypeOid::Int4,
                TypeOid::Float8Array,
                TypeOid::Float8,
            ],
            "{sql}"
        );
        assert!(columns.iter().all(|c| c.type_certain), "{sql}");
        // the operand: no column it defines is certain, alone or under a fold
        let sql = format!(
            "SELECT i + {unknown}, {unknown} * f, b - {unknown}, n / {unknown}, d - {unknown}, \
             COALESCE(n * {unknown}, n), COALESCE(i, f + {unknown}), greatest(i + {unknown}, i), \
             CASE WHEN k > 0 THEN f * {unknown} ELSE f END, ARRAY[i + {unknown}, i] FROM t"
        );
        assert_eq!(certain_flags(&schema, &sql), [false; 10], "{sql}");
        // and the pass casts a branch over one to the fold's target, whatever the
        // sibling operand's type: the value's type is not the sibling's to promise
        let Plan::Project { exprs, .. } = plan_select(
            &schema,
            &format!("SELECT COALESCE(n * {unknown}, n), COALESCE(i + {unknown}, i) FROM t"),
        ) else {
            panic!("a projection");
        };
        for (entry, target) in exprs.iter().zip([TypeOid::Numeric, TypeOid::Int4]) {
            let Expr::Coalesce(branches) = entry else {
                panic!("a fold: {entry:?}");
            };
            assert!(
                matches!(&branches[0], Expr::Cast { target_type, .. } if *target_type == target),
                "{unknown}: {:?}",
                branches[0]
            );
        }
        // an aggregate over one is not an aggregate over a certain integer
        let sql = format!(
            "SELECT avg(COALESCE({unknown}, i + 0)), avg(i + {unknown}), sum({unknown} * b), \
             avg(d - {unknown}), sum(COALESCE(b * {unknown}, b)) FROM t"
        );
        let plan = plan_select(&schema, &sql);
        let types: Vec<TypeOid> = plan
            .output_columns(&schema)
            .iter()
            .map(|c| c.type_oid)
            .collect();
        assert_eq!(
            types,
            [
                TypeOid::Numeric,
                TypeOid::Float8,
                TypeOid::Int8,
                TypeOid::Float8,
                TypeOid::Int8
            ],
            "{sql}"
        );
        let mut found = Vec::new();
        let mut node = &plan;
        loop {
            match node {
                Plan::Aggregate { exprs, input, .. } => {
                    for e in exprs {
                        verdicts(e, &mut found);
                    }
                    node = input;
                }
                Plan::Project { input, .. } => node = input,
                _ => break,
            }
        }
        assert_eq!(
            found,
            [
                ArgCertainty::CertainInteger(TypeOid::Int4),
                ArgCertainty::NotCertainInteger,
                ArgCertainty::NotCertainInteger,
                ArgCertainty::NotCertainInteger,
                ArgCertainty::NotCertainInteger
            ],
            "{sql}"
        );
    }
    // the parameter itself is cast to the fold's target, which is what describes it
    let Plan::Project { exprs, .. } = plan_select(&schema, "SELECT COALESCE($1, f + 0) FROM t")
    else {
        panic!("a projection");
    };
    let Expr::Coalesce(branches) = &exprs[0] else {
        panic!("a fold: {:?}", exprs[0]);
    };
    assert!(
        matches!(&branches[0], Expr::Cast { expr, target_type: TypeOid::Float8 }
            if matches!(**expr, Expr::Parameter { .. })),
        "{:?}",
        branches[0]
    );
    // two unknowns choose no target
    assert_eq!(
        certain_flags(&schema, "SELECT COALESCE($1, $2), -$1 FROM t"),
        [false, false]
    );
}

/// A `date` less a `date` is the one operator over two dates the branch reader types: its
