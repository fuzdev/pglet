#[test]
fn test_set_config_reads_its_setting_name_as_a_literal() {
    // The `search_path` gate is on the **request**, and a request whose setting name
    // the planner cannot read is one it cannot prove is not `search_path`. pglet does
    // not constant-fold before lowering, so `'search' || '_path'` and
    // `lower('SEARCH_PATH')` reached the arm as expressions and were echoed —
    // reproducing the original silent-wrong end to end (an unqualified read after
    // `set_config('search'||'_path','nosuch',false)` answered rows here and `42P01` on
    // 18.6). They are refused now: 18.6 accepts them, so this is pglet-stricter and
    // loud, which is the direction correct-or-loud takes when the engine cannot see
    // what it is being asked.
    let schema = Schema::new();
    let err_of = |sql: &str| {
        crate::parser::parse_single(sql, &schema)
            .expect_err(sql)
            .sqlstate()
            .to_string()
    };
    for sql in [
        "SELECT set_config('search' || '_path', 'nosuch', false)",
        "SELECT set_config(lower('SEARCH_PATH'), 'nosuch', false)",
        // Even for a value the gate would have accepted: the name is what cannot be
        // read, so the statement is refused whatever it asks for.
        "SELECT set_config('search' || '_path', 'public', false)",
        "SELECT set_config('x' || 'y', 'z', false)",
    ] {
        assert_eq!(err_of(sql), "0A000", "{sql}");
    }
    // A NULL name is 18.6's own `22004 SET requires parameter name`, raised before the
    // name is looked up — pglet used to echo the *value* and report success.
    assert_eq!(err_of("SELECT set_config(NULL, 'x', false)"), "22004");
    // A **cast** around a literal is still a literal name. The parser folds redundant
    // parentheses away, so `set_config(('search_path'), …)` always arrived here as one;
    // `'search_path'::text` did not, and the two spellings of one valid request
    // disagreed (18.6 accepts both). Peeling is faithful because the cast decides the
    // argument's type and this gate reads its value.
    for sql in [
        "SELECT set_config('search_path'::text, 'public', false)",
        "SELECT set_config(CAST('search_path' AS text), 'public', false)",
        "SELECT set_config(('search_path'), 'public', false)",
    ] {
        crate::parser::parse_single(sql, &schema).unwrap_or_else(|e| panic!("{sql}: {e}"));
    }
    // …and the peel reaches the gate, so a cast spelling cannot smuggle a bad list past
    // it either.
    assert_eq!(
        err_of("SELECT set_config('search_path'::text, 'nosuch', false)"),
        "0A000"
    );
    // A literal name that is not a checked GUC still echoes, including with a computed
    // value — the shape every `set_config` walker pin depends on.
    for sql in [
        "SELECT set_config('x', 'y', false)",
        "SELECT set_config('statement_timeout', '0', false)",
    ] {
        crate::parser::parse_single(sql, &schema).unwrap_or_else(|e| panic!("{sql}: {e}"));
    }
}

#[test]
fn test_set_config_takes_a_fixed_parameter_only_at_the_value_pglet_has() {
    // The function route of the fixed-parameter gate: the `SET` statement's decider, reached
    // by `set_config`, with `is_local` not entering the decision. An accepted spelling lowers
    // to the value the parameter has — 18.6 returns the setting as it now stands (`UTC` for
    // `'utc'`), not the argument.
    let schema = Schema::new();
    let err_of = |sql: &str| {
        crate::parser::parse_single(sql, &schema)
            .expect_err(sql)
            .sqlstate()
            .to_string()
    };
    for (sql, value) in [
        ("SELECT set_config('TimeZone', 'utc', false)", "UTC"),
        ("SELECT set_config('timezone', 'UTC', true)", "UTC"),
        ("SELECT set_config('timezone'::text, 'UTC', false)", "UTC"),
        // a NULL value is a reset, and the answer is the restored value
        ("SELECT set_config('timezone', NULL, false)", "UTC"),
        ("SELECT set_config('DateStyle', 'iso', false)", "ISO, MDY"),
        (
            "SELECT set_config('IntervalStyle', 'POSTGRES', false)",
            "postgres",
        ),
        (
            "SELECT set_config('standard_conforming_strings', 'true', false)",
            "on",
        ),
    ] {
        let plan = plan_select(&schema, sql);
        let result = crate::executor::execute(&plan, &mut Schema::new())
            .unwrap_or_else(|e| panic!("{sql}: {e}"));
        assert_eq!(
            result.rows,
            vec![vec![crate::types::Value::Text(value.into())]],
            "{sql}"
        );
    }
    for sql in [
        "SELECT set_config('TimeZone', 'America/New_York', false)",
        "SELECT set_config('timezone', 'America/New_York', true)",
        "SELECT set_config('timezone', 'GMT', false)",
        "SELECT set_config('DateStyle', 'German', false)",
        "SELECT set_config('intervalstyle', 'iso_8601', false)",
        "SELECT set_config('standard_conforming_strings', 'off', false)",
        // a value the planner cannot read is one it cannot prove is the fixed one
        "SELECT set_config('timezone', 'U' || 'TC', false)",
        "SELECT set_config('datestyle', lower('ISO'), false)",
        // the session's own values move through `SET` alone
        "SELECT set_config('application_name', 'probe', false)",
        "SELECT set_config('application_name', NULL, false)",
        "SELECT set_config('lock_timeout', '5s', false)",
        "SELECT set_config('lock_timeout', '0', true)",
    ] {
        assert_eq!(err_of(sql), "0A000", "{sql}");
    }
    // 18.6's own verdict comes first, as it does through `SET`.
    assert_eq!(
        err_of("SELECT set_config('standard_conforming_strings', 'maybe', false)"),
        "22023"
    );
}

